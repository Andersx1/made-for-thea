// Builds src/assets/body-data.js from the MakeHuman base mesh and body-shape targets (CC0).
// Run once with:  node tools/build-body.mjs   (downloads ~6 MB into tools/.cache the first time)
// Output: body vertices (cm), triangles, measurement vertex loops, and sparse target deltas.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cache = path.join(here, '.cache');
const out = path.join(here, '..', 'src', 'assets', 'body-data.js');
const BASE = 'https://raw.githubusercontent.com/makehumancommunity/makehuman/master/makehuman';
const BODY_VERTS = 13380; // vertices 0..13379 are the body; the rest are helper geometry

const MEASURES = ['ankle-circ', 'bust-circ', 'calf-circ', 'frontchest-dist', 'hips-circ', 'knee-circ', 'lowerarm-length', 'lowerleg-height', 'napetowaist-dist',
  'neck-circ', 'neck-height', 'shoulder-dist', 'thigh-circ', 'underbust-circ', 'upperarm-circ', 'upperarm-length', 'upperleg-height', 'waist-circ', 'waisttohip-dist', 'wrist-circ'];
const TARGETS = [
  ...MEASURES.flatMap((m) => [`measure/measure-${m}-decr`, `measure/measure-${m}-incr`]),
  'macrodetails/african-female-young', 'macrodetails/asian-female-young', 'macrodetails/caucasian-female-young',
  'macrodetails/universal-female-young-averagemuscle-maxweight', 'macrodetails/universal-female-young-averagemuscle-minweight',
  'macrodetails/height/female-young-averagemuscle-averageweight-maxheight', 'macrodetails/height/female-young-averagemuscle-averageweight-minheight',
  'breast/female-young-averagemuscle-averageweight-maxcup-averagefirmness', 'breast/female-young-averagemuscle-averageweight-mincup-averagefirmness',
];

async function get(rel) {
  const file = path.join(cache, rel);
  if (fs.existsSync(file)) return fs.readFileSync(file, 'utf8');
  const res = await fetch(`${BASE}/${rel}`);
  if (!res.ok) throw new Error(`${rel}: HTTP ${res.status}`);
  const text = await res.text();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return text;
}
const b64 = (typed) => Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString('base64');

const obj = await get('data/3dobjs/base.obj');
const verts = new Float32Array(BODY_VERTS * 3), tris = [];
let vi = 0, group = null;
for (const line of obj.split('\n')) {
  if (line.startsWith('v ')) { if (vi < BODY_VERTS) { const [x, y, z] = line.split(/\s+/).slice(1, 4).map(Number); verts.set([x * 10, y * 10, z * 10], vi * 3); } vi++; }
  else if (line.startsWith('g ')) group = line.split(/\s+/)[1];
  else if (line.startsWith('f ') && group === 'body') {
    const f = line.trim().split(/\s+/).slice(1).map((t) => parseInt(t, 10) - 1);
    for (let k = 1; k < f.length - 1; k++) tris.push(f[0], f[k], f[k + 1]); // quads → triangles
  }
}

// Measurement loops (vertex index paths) from MakeHuman's measurement plugin.
const plugin = await get('plugins/0_modeling_a_measurement.py');
const loops = {};
for (const [, name, list] of plugin.matchAll(/Measures\['measure\/measure-([a-z-]+)-decr\|incr'\]\s*=\s*\[([\d,\s]+)\]/g)) loops[name] = list.split(',').map((s) => parseInt(s, 10));

const targets = {};
for (const t of TARGETS) {
  const idx = [], d = [];
  for (const line of (await get(`data/targets/${t}.target`)).split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [i, x, y, z] = line.trim().split(/\s+/).map(Number);
    if (i < BODY_VERTS) { idx.push(i); d.push(x * 10, y * 10, z * 10); }
  }
  targets[t.split('/').pop()] = { idx: b64(new Uint16Array(idx)), d: b64(new Float32Array(d)) };
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by tools/build-body.mjs from the MakeHuman base mesh and targets.
// MakeHuman assets are CC0 (public domain): https://www.makehumancommunity.org
export const BODY = ${JSON.stringify({ count: BODY_VERTS, verts: b64(verts), tris: b64(new Uint16Array(tris)), loops, targets })};
`);
console.log(`body: ${BODY_VERTS} vertices, ${tris.length / 3} triangles, ${Object.keys(loops).length} measurement loops, ${Object.keys(targets).length} targets → ${(fs.statSync(out).size / 1e6).toFixed(1)} MB`);
